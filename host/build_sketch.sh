#!/usr/bin/env bash
# Build an Arduino sketch for the SMC-PAD on this Linux host, without Docker, and (--flash)
# send it to the pad through the bootloader.
#
#   host/build_sketch.sh [<sketch dir>] [--flash] [--core]
#
# Default sketch: arduino/sketches/PocketDemo. Output: work/sketch/<name>/<name>.bin -- the
# application's app area, exactly what host/dfu_flash.sh takes for DFU alternate 0. --flash
# runs that too (it needs access to the pad's serial port: sudo where there is no udev rule).
#
# The sketch is linked against the precompiled Arduino core that fw/build.sh builds in Docker
# (SMCPAD_ARDUINO=1 SMCPAD_TINYUSB=1). Here that core is built natively with the JieLi
# toolchain, into arduino/smcpad/system/ (what arduino/make_system.sh installs for the Arduino
# IDE); it is rebuilt when a runtime source is newer, or always with --core. The JieLi
# toolchain must run on this machine (Linux x86-64): JL_TOOLCHAIN, else tools/jl-toolchain/,
# else /opt/jieli. Needs: the SDK submodule, python3 (the area template) and cc (the packer).
set -euo pipefail
shopt -s nullglob

die() { echo "!! $*" >&2; exit 1; }

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SKETCH=""
FLASH=0
FORCE_CORE=0
for arg in "$@"; do
    case "$arg" in
        --flash) FLASH=1 ;;
        --core)  FORCE_CORE=1 ;;
        -*)      die "unknown option $arg (usage: host/build_sketch.sh [<sketch dir>] [--flash] [--core])" ;;
        *)       SKETCH="$arg" ;;
    esac
done
SKETCH="${SKETCH:-$ROOT/arduino/sketches/PocketDemo}"
SKETCH="$(cd "$SKETCH" && pwd)" || die "no such sketch directory"
NAME="$(basename "$SKETCH")"
[ -f "$SKETCH/$NAME.ino" ] || die "no $NAME.ino in $SKETCH"

SDK="$ROOT/sdk/fw-AC63_BT_SDK"
[ -d "$SDK/apps" ] || die "the SDK submodule is missing: git submodule update --init sdk/fw-AC63_BT_SDK"
TOOLCHAIN="${JL_TOOLCHAIN:-}"
if [ -z "$TOOLCHAIN" ]; then
    tc=( "$ROOT"/tools/jl-toolchain/jieli-linux-toolchains-*/ )
    [ ${#tc[@]} -gt 0 ] && TOOLCHAIN="${tc[0]}"
fi
TOOLCHAIN="${TOOLCHAIN:-/opt/jieli}"
TOOLCHAIN="${TOOLCHAIN%/}"
T="$TOOLCHAIN/pi32v2/bin"
[ -x "$T/clang" ] || die "no JieLi toolchain at $TOOLCHAIN (set JL_TOOLCHAIN)"

PLAT="$ROOT/arduino/smcpad"
CORE="$PLAT/system"
OUT="$ROOT/work/sketch/$NAME"
TEXT_BASE=0x1E08120                  # app.bin at flash 0x9120 (application area 0x9000)

# ------------------------------------------------------------------ the core (once)

core_stale() {
    [ -f "$CORE/smcpad_core.o" ] && [ -f "$CORE/sdk.ld" ] && [ -f "$CORE/libsmcpad_native.a" ] \
        || return 0
    local newer
    newer="$(find "$ROOT/fw/smcpad" \( -path "$ROOT/fw/smcpad/out" -o -name smcpad_usb_build.h \) -prune \
                  -o -type f -newer "$CORE/smcpad_core.o" -print -quit)"
    [ -n "$newer" ]
}

build_core() {
    local APP="$SDK/apps/smcpad" TOOLS="$SDK/cpu/br25/tools" LOG="$ROOT/build_logs/sketch_core.log" N
    echo "== building the Arduino core (SMCPAD_ARDUINO=1, TinyUSB) into $CORE"
    mkdir -p "$ROOT/build_logs"
    # The Docker build mounts fw/smcpad over the SDK's apps/smcpad; natively it is a copy, so
    # keep it in sync (the SDK's out/ and objs/ stay).
    rsync -a --delete --exclude out --exclude objs "$ROOT/fw/smcpad/" "$APP/"
    { printf '#define SMCPAD_TINYUSB %s\n' 1
      printf '#define SMCPAD_APP_DIR %s\n' 0x9000
      printf '#define SMCPAD_ARDUINO %s\n' 1
      printf '#define SMCPAD_POCKET %s\n' 1; } > "$APP/usb/smcpad_usb_build.h"
    (
        cd "$APP/board/br25"
        rm -f "$TOOLS/sdk.elf"
        make TOOL_DIR="$T" pre_build 2>&1 | grep -v "stack size limit" || true
        # same linker-script patches fw/build.sh applies (sdk_ld.c hardcodes the factory layout)
        local LD="$SDK/cpu/br25/sdk.ld"
        sed -i "s/ORIGIN =  *0x1E00120/ORIGIN = $TEXT_BASE/" "$LD"
        grep -q "ORIGIN = $TEXT_BASE" "$LD" || die "sdk.ld: could not move the app to $TEXT_BASE"
        sed -i "s/^RAM_LIMIT_H = UPDATA_BEG;/SMCPAD_NOINIT = UPDATA_BEG - 0x400;\nRAM_LIMIT_H = SMCPAD_NOINIT;/" "$LD"
        sed -i "s/^\( *\)chip_reset = ABSOLUTE(0x117fcc);/\1chip_reset = smcpad_chip_reset;\n\1smcpad_rom_chip_reset = ABSOLUTE(0x117fcc);/" "$LD"
        grep -q "smcpad_rom_chip_reset" "$LD" || die "sdk.ld: could not route chip_reset"
        cat ../../arduino/api.symbols >> "$SDK/cpu/br25/sdk_used_list.used"
        # the runtime API stays global for the sketch (referenced from a non-LTO object, which
        # the LTO plugin has to honour; the used list alone only keeps the code)
        mkdir -p objs
        { echo "/* generated by host/build_sketch.sh from api.symbols */"
          while read -r sym; do [ -n "$sym" ] && echo "extern char $sym[];"; done < ../../arduino/api.symbols
          echo "void *const smcpad_api_keep[] __attribute__((used)) = {"
          while read -r sym; do [ -n "$sym" ] && echo "    $sym,"; done < ../../arduino/api.symbols
          echo "};"; } > objs/api_keep.c
        "$T/clang" -target pi32v2 -mcpu=r3 -Oz -ffreestanding -fno-builtin -w \
            -c objs/api_keep.c -o objs/api_keep.o
        if ! SMCPAD_LFLAGS="--unresolved-symbols=ignore-all objs/api_keep.o" \
                make TOOL_DIR="$T" -j"${JOBS:-$(nproc 2>/dev/null || echo 4)}" ../../../../cpu/br25/tools/sdk.elf \
                > "$LOG" 2>&1; then
            tail -30 "$LOG" >&2
            die "the core build failed (full log: $LOG)"
        fi
    )
    mkdir -p "$CORE/include" "$ROOT/fw/smcpad/out/core"
    cp "$TOOLS/sdk.elf.o" "$CORE/smcpad_core.o"
    cp "$TOOLS/sdk.elf" "$ROOT/fw/smcpad/out/sdk.elf"
    cp "$TOOLS/sdk.elf.o" "$TOOLS/sdk.elf" "$CORE/sdk.ld" "$ROOT/fw/smcpad/out/core/" 2>/dev/null || true
    cp "$ROOT/fw/smcpad/arduino/smcpad_rt.h" "$CORE/include/"
    # + C++ constructors (.init_array and .ctors, walked by smcpad_arduino_run()), and .bss.*:
    # sketches compile with -fdata-sections, and a global in an orphan section past bss_end
    # would never be cleared (the SDK script only takes .bss)
    awk '/^        \*\(\.rodata\*\)$/ && !done { print "        . = ALIGN(4);"; print "        __init_array_start = .;"; print "        KEEP(*(SORT(.init_array.*)))"; print "        KEEP(*(.init_array))"; print "        KEEP(*(SORT(.ctors.*)))"; print "        KEEP(*(.ctors))"; print "        __init_array_end = .;"; done = 1 } { print }' \
        "$SDK/cpu/br25/sdk.ld" > "$CORE/sdk.ld"
    grep -q __init_array_start "$CORE/sdk.ld" || die "sdk.ld: no init_array block"
    sed -i "s/^        \*(\.bss)\$/        *(.bss)\n        *(.bss.*)/" "$CORE/sdk.ld"
    grep -q "^\s*\*(\.bss\.\*)\$" "$CORE/sdk.ld" || die "sdk.ld: no .bss.* rule"
    # the ROM sprintf has no floating point: sketches use the core's printf.c instead
    sed -i "/^  sprintf = ABSOLUTE(/d" "$CORE/sdk.ld"
    ! grep -q "^  sprintf = ABSOLUTE(" "$CORE/sdk.ld" || die "sdk.ld: ROM sprintf still bound"
    # the native (non-bitcode) SDK archive members a plain ld may still need
    N="$(mktemp -d)"
    rm -f "$CORE/libsmcpad_native.a"
    local a abs d o
    for a in "$SDK"/cpu/br25/liba/*.a; do
        abs="$(realpath "$a")"; d="$N/$(basename "$a" .a)"; mkdir -p "$d"
        ( cd "$d" && "$T/ar" x "$abs" )
        for o in "$d"/*; do
            if [ "$(head -c 4 "$o" | od -An -c | tr -d ' ')" = "177ELF" ]; then
                cp "$o" "$N/$(basename "$a" .a)__$(basename "$o")"
            fi
        done
    done
    "$T/ar" rcs "$CORE/libsmcpad_native.a" "$N"/*__* 2>/dev/null \
        || "$T/ar" rcs "$CORE/libsmcpad_native.a"
    rm -rf "$N"
    cp "$CORE/sdk.ld" "$CORE/libsmcpad_native.a" "$ROOT/fw/smcpad/out/core/"
}

if [ "$FORCE_CORE" = 1 ] || core_stale; then
    build_core
else
    echo "== core: $CORE (up to date; --core rebuilds it)"
fi

# ------------------------------------------------------------------ host tools

PACK="$PLAT/tools/host/smcpad_pack"
if [ ! -x "$PACK" ] || [ "$PLAT/tools/smcpad_pack.c" -nt "$PACK" ]; then
    mkdir -p "$PLAT/tools/host"
    cc -O2 -o "$PACK" "$PLAT/tools/smcpad_pack.c"
fi
[ -f "$CORE/app_template.bin" ] || python3 "$ROOT/arduino/release/make_template.py" "$CORE/app_template.bin"

# ------------------------------------------------------------------ the sketch

rm -rf "$OUT"
mkdir -p "$OUT"

INC=(-I"$PLAT/cores/smcpad" -I"$PLAT/variants/smcpad" -I"$CORE/include")
for d in "$PLAT"/libraries/*/src; do INC+=(-I"$d"); done
DEF=(-DARDUINO=10607 -DARDUINO_SMCPAD -DARDUINO_ARCH_BR25 -DSMCPAD)
COMMON=(-target pi32v2 -mcpu=r3 -integrated-as -Oz -fno-common -ffunction-sections
        -fdata-sections -mllvm -enable-ipra=false -isystem "$TOOLCHAIN/pi32v2/include" -w)
CXX=("$T/clang++" "${COMMON[@]}" -std=gnu++14 -fno-exceptions -fno-rtti -fno-threadsafe-statics
     -fno-use-cxa-atexit "${DEF[@]}" "${INC[@]}")
CC=("$T/clang" "${COMMON[@]}" -std=gnu11 "${DEF[@]}" "${INC[@]}")

echo "== compiling $NAME"
# arduino-cli would preprocess the .ino (adding Arduino.h and prototypes); the sketches here are
# written helper-first, so including it after Arduino.h is enough and needs no preprocessor.
"${CXX[@]}" -c -x c++ -o "$OUT/sketch.o" - <<EOF
#include <Arduino.h>
#include "$SKETCH/$NAME.ino"
EOF
for f in "$PLAT"/cores/smcpad/*.cpp "$PLAT"/cores/smcpad/api/*.cpp; do
    "${CXX[@]}" -c "$f" -o "$OUT/core_$(basename "$f").o"
done
for f in "$PLAT"/cores/smcpad/*.c; do
    "${CC[@]}" -c "$f" -o "$OUT/core_$(basename "$f").o"
done
# every bundled library, as arduino-cli would include them: ld drops what the sketch never uses
for f in "$PLAT"/libraries/*/src/*.cpp "$PLAT"/libraries/*/src/*.c; do
    case "$f" in
        *.cpp) "${CXX[@]}" -c "$f" -o "$OUT/lib_$(basename "$f").o" ;;
        *.c)   "${CC[@]}"  -c "$f" -o "$OUT/lib_$(basename "$f").o" ;;
    esac
done

echo "== linking"
if ! "$T/ld" -o "$OUT/$NAME.elf" "$OUT"/*.o "$CORE/smcpad_core.o" \
        --start-group "$CORE/libsmcpad_native.a" \
            "$TOOLCHAIN/pi32v2/lib/r3/libc.a" "$TOOLCHAIN/pi32v2/lib/r3/libm.a" \
            "$TOOLCHAIN/pi32v2/lib/r3/libcompiler-rt.a" --end-group \
        -T "$CORE/sdk.ld" --gc-sections --sort-common --dont-complain-call-overflow \
        -Map "$OUT/$NAME.map" 2> "$OUT/ld.log"; then
    grep -v "warning:" "$OUT/ld.log" >&2 || true
    die "link failed"
fi
"$PACK" "$OUT/$NAME.elf" "$OUT/$NAME.bin" --template "$CORE/app_template.bin"
"$PACK" "$OUT/$NAME.elf" "$OUT/$NAME.size.bin" --template "$CORE/app_template.bin" --size
rm -f "$OUT/$NAME.size.bin" "$OUT/ld.log"

echo "== $OUT/$NAME.bin"
if [ "$FLASH" = 1 ]; then
    exec "$ROOT/host/dfu_flash.sh" "$OUT/$NAME.bin"
fi
