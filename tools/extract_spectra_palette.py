#!/usr/bin/env python3
"""Generate SpectraPalette.h from the Midi Fighter Spectra guide's Fig 2.

The guide prints the velocity bands as circles: the bright half is a flat vector fill, the
dim half is the same fill hatched with black (there is no second flat colour), and the last
circle is white/black for 115-120 / 1-6.  The bright fills are read from the PDF's vector
content (exact); the dim entries are half of them, except the printed black 1-6 swatch.

    tools/extract_spectra_palette.py [--pdf /tmp/spectra.pdf] [--page 9]
        [--out arduino/sketches/MidiFighterSpectra/SpectraPalette.h]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

# Fig 2's layout (printed page 8): two rows of five circles, each with its bright band on the
# upper label line and the dim band below.  Cell -> first velocity of the bright band.
ROWS = [
    [7, 31, 55, 79, 103],
    [19, 43, 67, 91, 115],
]

HEADER = """\
// Generated by tools/extract_spectra_palette.py from the Midi Fighter Spectra User Guide
// (Ver 1.01), Fig 2 "MIDI Color Velocity Settings" (PDF p. {page}, printed p. 8).
// Do not edit by hand; rerun the tool.  Bright entries are the guide's exact swatch fills.
// The guide prints the dim state as hatching over the same fill, so dim = 50% of bright;
// the 1-6 swatch is literally black (dim white) and velocity 121-127 forces the Utility
// active colour instead.
#pragma once
#include <stdint.h>

#define SPECTRA_PALETTE_SIZE 20

static const uint32_t SPECTRA_PALETTE[SPECTRA_PALETTE_SIZE] = {{
{entries}
}};

// 1..120 -> palette index; 0 disables MIDI colour control; 121..127 force the active colour.
static inline int spectraColorIndex(uint8_t velocity) {{
    if (velocity == 0) return -1;
    if (velocity >= 121) return -2;
    return (velocity - 1) / 6;
}}
"""


def circle_colors(svg):
    """(center x, center y, '#RRGGBB') for the 10 Fig 2 circles, top-to-bottom, left-to-right."""
    paths = []
    for m in re.finditer(r'<path[^>]*fill="rgb\(([^)]*)\)"[^>]*d="([^"]+)"', svg):
        r, g, b = (float(p.strip('%')) for p in m.group(1).split(','))
        nums = [float(n) for n in re.findall(r'-?\d+\.?\d*', m.group(2))]
        xs, ys = nums[0::2], nums[1::2]
        w, h = max(xs) - min(xs), max(ys) - min(ys)
        paths.append((m.group(1), r, g, b, xs, ys, w, h))
    counts = {}
    for fill, *_ in paths:
        counts[fill] = counts.get(fill, 0) + 1
    full, half_disc = [], []
    for fill, r, g, b, xs, ys, w, h in paths:
        # The ten swatches are the only paths using their fill once; the white swatch is a
        # half disc in local coordinates (the black bottom is drawn separately).
        if counts[fill] != 1 or max(r, g, b) < 25:
            continue
        if not (45 < w < 55 and 15 < h < 55):
            continue
        rgb = '#%02X%02X%02X' % tuple(round(v * 2.55) for v in (r, g, b))
        center = ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2, rgb)
        (half_disc if h < 40 else full).append(center)
    if len(full) != 9 or len(half_disc) != 1:
        sys.exit('expected 9 circles and the white half disc, found %d/%d'
                 % (len(full), len(half_disc)))
    full.sort(key=lambda c: c[1])
    top, bottom = full[:5], full[5:]
    for row in (top, bottom):
        row.sort(key=lambda c: c[0])
    found = top + bottom + half_disc              # the white half disc is the last cell
    return found


def half(hex_rgb):
    r, g, b = (int(hex_rgb[i:i + 2], 16) // 2 for i in (1, 3, 5))
    return '#%02X%02X%02X' % (r, g, b)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--pdf', default='/tmp/spectra.pdf')
    ap.add_argument('--page', type=int, default=9)
    ap.add_argument('--out', default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), '..', 'arduino', 'sketches',
        'MidiFighterSpectra', 'SpectraPalette.h'))
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        svg_path = os.path.join(tmp, 'page.svg')
        subprocess.run(['pdftocairo', '-svg', '-f', str(args.page), '-l', str(args.page),
                        args.pdf, svg_path], check=True, capture_output=True)
        with open(svg_path, encoding='utf-8', errors='replace') as f:
            circles = circle_colors(f.read())

    palette = [None] * 20                              # index = (first velocity - 1) / 6
    for row, bands in enumerate(ROWS):
        for col, first in enumerate(bands):
            _, _, bright = circles[row * 5 + col]
            idx = (first - 1) // 6
            palette[idx] = bright
            dim_idx = (idx + 1) % 20
            palette[dim_idx] = half(bright) if dim_idx else '#000000'   # 1-6 is black
    if any(c is None for c in palette):
        sys.exit('palette incomplete: %r' % palette)

    entries = []
    for i, c in enumerate(palette):
        first = 6 * i + 1
        state = 'bright' if i % 2 else 'dim'
        note = ' (black: dim white)' if i == 0 else ''
        entries.append('    0x%su,  // %3d-%3d %s%s' % (c[1:], first, first + 5, state, note))

    with open(args.out, 'w') as f:
        f.write(HEADER.format(page=args.page, entries='\n'.join(entries)))
    print(args.out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
